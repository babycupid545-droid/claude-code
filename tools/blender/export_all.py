"""Builds every Blender asset, trims it to a mobile-friendly triangle budget, and writes:

  assets/models/Chicken.glb   assets/models/Vehicles.glb   assets/models/Props.glb
  (plus .fbx copies, for Studio versions whose importer doesn't take .glb)
  src/builders/MeshManifest.luau   (authored centre + size of every mesh, in studs)
  docs/previews/blender_*.jpg      (optional, with --previews)

glTF uses Roblox's own axes (x right, y up, z back), so nothing gets rotated on import.
The Studio builders read the manifest to place and size each imported MeshPart, so the
importer's unit scale or re-centring doesn't matter.

Run:  cd tools/blender && python3 export_all.py [--previews]
"""

import os
import sys

import bpy  # noqa: F401
from mathutils import Vector

import common as C
import chicken
import props
import vehicles

OUT = os.path.join(C.ROOT, "assets", "models")
MANIFEST = os.path.join(C.ROOT, "src", "builders", "MeshManifest.luau")
PREVIEW_CACHE = os.path.join(C.ROOT, "tools", "preview", ".cache", "meshes.txt")

# Triangle budgets per colour region (keeps a whole lobby of chickens cheap on phones).
BUDGET = {
    "Chicken": {"Body": 2600, "Head": 2200, "WingL": 1300, "WingR": 1300, "Tail": 1400, "Belly": 700,
                "Comb": 700, "LegL": 600, "LegR": 600, "_": 400},
    "_vehicle": {"_": 1400},
    "_prop": {"Cloud": 1200, "_": 1600},
}


def budget_for(group, asset, key):
    table = BUDGET.get(asset) or BUDGET[group]
    return table.get(key, table["_"])


def limit(obj, max_tris):
    tris = C.tri_count(obj)
    if tris <= max_tris:
        return
    dec = obj.modifiers.new("budget", "DECIMATE")
    dec.ratio = max_tris / tris
    C.apply_all(obj)
    C.shade(obj, True)


def bounds(obj):
    """Axis-aligned bounds in Roblox coords."""
    pts = [obj.matrix_world @ v.co for v in obj.data.vertices]
    rb = [(p.x, p.z, -p.y) for p in pts]
    lo = [min(p[i] for p in rb) for i in range(3)]
    hi = [max(p[i] for p in rb) for i in range(3)]
    return lo, hi


def colour_materials(objs, palette):
    for o in objs:
        asset, key = o.name.split("__")
        rgb = palette(asset, key)
        C.set_material(o, C.material(f"{asset}_{key}", rgb, 0.5))


def export_glb(path, objs):
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    for o in objs:
        o.select_set(True)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=True,
        export_normals=True,
        export_materials="EXPORT",
        export_animations=False,
    )


def collect(group, module, palette):
    C.reset()
    objs = module.build()
    out = []
    for o in objs:
        if "__" not in o.name:
            continue
        asset, key = o.name.split("__")
        limit(o, budget_for(group, asset, key))
        o.data.name = o.name
        out.append(o)
    colour_materials(out, palette)
    entries = {}
    for o in out:
        asset, key = o.name.split("__")
        lo, hi = bounds(o)
        entries.setdefault(asset, []).append((key, lo, hi, C.tri_count(o)))
    return out, entries


def lua_num(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def write_manifest(all_entries):
    lines = [
        "--!strict",
        "-- GENERATED by tools/blender/export_all.py; do not edit by hand.",
        "-- Authored centre and size (studs) of every mesh region, per asset, so imported",
        "-- MeshParts can be placed and sized exactly however the importer scaled them.",
        "-- Asset space: base at y = 0, centred on x/z, facing -z.",
        "",
        "export type Region = { center: Vector3, size: Vector3, tris: number }",
        "export type Asset = { file: string, size: Vector3, regions: { [string]: Region } }",
        "",
        "local V = Vector3.new",
        "",
        "local Manifest: { [string]: Asset } = {",
    ]
    for file, entries in all_entries:
        for asset in sorted(entries):
            regs = entries[asset]
            alo = [min(r[1][i] for r in regs) for i in range(3)]
            ahi = [max(r[2][i] for r in regs) for i in range(3)]
            size = [ahi[i] - alo[i] for i in range(3)]
            lines.append(f"\t{asset} = {{")
            lines.append(f'\t\tfile = "{file}",')
            lines.append(f"\t\tsize = V({', '.join(lua_num(v) for v in size)}),")
            lines.append("\t\tregions = {")
            for key, lo, hi, tris in sorted(regs):
                c = [(lo[i] + hi[i]) / 2 for i in range(3)]
                s = [max(hi[i] - lo[i], 0.05) for i in range(3)]
                lines.append(f"\t\t\t{key} = {{ center = V({', '.join(lua_num(v) for v in c)}), "
                             f"size = V({', '.join(lua_num(v) for v in s)}), tris = {tris} }},")
            lines.append("\t\t},")
            lines.append("\t},")
    lines += ["}", "", "return Manifest", ""]
    with open(MANIFEST, "w") as f:
        f.write("\n".join(lines))


def preview(path, objs, eye, target, size=(900, 700), lens=40, ground=60, ground_rgb=(140, 200, 120)):
    C.preview_setup(size[0], size[1], 32)
    C.ground(ground, ground_rgb)
    C.camera(eye, target, lens)
    C.render(path)


def main():
    previews = "--previews" in sys.argv
    prev_dir = os.path.join(C.ROOT, "docs", "previews")
    all_entries = []
    os.makedirs(os.path.dirname(PREVIEW_CACHE), exist_ok=True)
    cache = open(PREVIEW_CACHE, "w")

    def dump(objs):
        # Triangles for tools/preview (renders Studio builds with these meshes: --meshes).
        for o in objs:
            me = o.data
            me.calc_loop_triangles()
            cache.write(f"o {o.name}\n")
            for tri in me.loop_triangles:
                pts = []
                for vi in tri.vertices:
                    v = o.matrix_world @ me.vertices[vi].co
                    pts.append(f"{v.x:.3f} {v.z:.3f} {-v.y:.3f}")
                cache.write("t " + " ".join(pts) + "\n")

    def chick_col(asset, key):
        return chicken.PREVIEW_COLORS.get(key, (200, 200, 200))

    objs, entries = collect("Chicken", chicken, chick_col)
    export_glb(os.path.join(OUT, "Chicken.glb"), objs)
    C.export_fbx(os.path.join(OUT, "Chicken.fbx"), objs)
    dump(objs)
    all_entries.append(("Chicken.glb", entries))
    print("Chicken tris:", sum(C.tri_count(o) for o in objs))
    if previews:
        for o in objs:
            if o.name.split("__")[1].startswith("Lid"):
                o.hide_render = True
        preview(os.path.join(prev_dir, "blender_chicken.png"), objs, (-6.5, 5.6, -9.5), (0, 2.7, 0), (800, 800), 50, 40)

    def car_col(asset, key):
        if key == "Body":
            return vehicles.BODY[asset]
        return vehicles.PREVIEW.get(key, (200, 200, 200))

    objs, entries = collect("_vehicle", vehicles, car_col)
    export_glb(os.path.join(OUT, "Vehicles.glb"), objs)
    C.export_fbx(os.path.join(OUT, "Vehicles.fbx"), objs)
    dump(objs)
    all_entries.append(("Vehicles.glb", entries))
    print("Vehicle tris:", sum(C.tri_count(o) for o in objs))

    def prop_col(asset, key):
        return props.PREVIEW.get(key, (200, 200, 200))

    objs, entries = collect("_prop", props, prop_col)
    export_glb(os.path.join(OUT, "Props.glb"), objs)
    C.export_fbx(os.path.join(OUT, "Props.fbx"), objs)
    dump(objs)
    all_entries.append(("Props.glb", entries))
    print("Prop tris:", sum(C.tri_count(o) for o in objs))

    cache.close()
    write_manifest(all_entries)
    print("Wrote", MANIFEST)


if __name__ == "__main__":
    main()
